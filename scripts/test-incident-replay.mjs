import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";
import { expect } from "@playwright/test";

export async function testIncidentReplay({ call, pool, page, frontend, machine, shift, adminId, viewer }) {
  const at = (second) => new Date(Date.UTC(2026, 1, 1, 12, 0, second)).toISOString();
  const query = (changes = {}) => new URLSearchParams({ start: at(0), end: at(60), keys: "ReplayCount", maxGapSeconds: "5", ...changes });
  const url = `/api/v1/production/replay/${machine.id}`;
  const other = (await pool.query("SELECT id FROM machines WHERE id<>$1 ORDER BY id LIMIT 1", [machine.id])).rows[0];
  const identity = { signalId: "owned-replay", endpointUrl: "opc.tcp://localhost:4842", machineId: machine.id, nodeId: "ns=2;s=ReplayCount", namespaceUri: "urn:owned:replay", identifier: "s=ReplayCount", mappingRevision: "v1", unit: "parts" };
  for (const [second, value, quality] of [[0, 10, "Good"], [1, 999, "BadNoCommunication"], [2, 12, "Good"], [20, 20, "Good"]])
    await pool.query("INSERT INTO opcua_data(machine_id,node_key,timestamp,source_timestamp,received_at,value,raw_value,status_code,signal_metadata) VALUES ($1,'ReplayCount',$2,$3,$4,$5,$6,$7,$8)", [machine.id, at(second), second === 2 ? null : at(second - 1), at(second + 10), value, JSON.stringify(value), quality, second === 2 ? null : identity]);
  await pool.query("INSERT INTO opcua_data(machine_id,node_key,timestamp,value,raw_value,status_code) VALUES ($1,'ReplayText',$2,NULL,$3,'Good'),($4,'ReplayCount',$2,123456,'123456','Good')", [machine.id, at(3), JSON.stringify("x".repeat(600)), other.id]);
  const incident = (await pool.query("INSERT INTO alert_history(machine_id,rule_name,message,created_at,acknowledged_at,acknowledged_by,resolved_at,metadata) VALUES ($1,'Replay alarm','Owned interruption',$2,$3,$4,$5,$6) RETURNING id", [machine.id, at(-1), at(1), adminId, at(20), { sourceTime: at(-2), lastSourceTime: at(19) }])).rows[0];
  const entry = (await pool.query("INSERT INTO operator_entries(machine_id,request_id,kind,text,created_by) VALUES ($1,$2,'note','CURRENT TEXT MUST NOT REWRITE HISTORY',$3) RETURNING id", [machine.id, randomUUID(), adminId])).rows[0];
  await pool.query("INSERT INTO operator_entry_events(entry_id,actor_id,version,snapshot,created_at) VALUES ($1,$2,1,$3,$4),($1,$2,2,$5,$6)", [entry.id, adminId, { kind: "note", text: "Owned original operator observation", status: "open" }, at(2), { kind: "note", text: "Owned corrected operator observation", status: "resolved" }, at(3)]);
  const replayShift = (await pool.query("INSERT INTO production_shifts(machine_id,name,timezone,start,\"end\",profile,job,breaks,created_by) SELECT machine_id,'Owned replay shift','UTC',$2,$3,profile,job,'[]',created_by FROM production_shifts WHERE id=$1 RETURNING id", [shift.id, at(0), at(60)])).rows[0];
  const reason = (await pool.query("INSERT INTO downtime_reasons(shift_id,start,\"end\",category,reason,actor_id,created_at) VALUES ($1,$2,$3,'unplanned','Owned later classification',$4,$5) RETURNING id", [replayShift.id, at(1), at(20), adminId, at(90)])).rows[0];
  let response = await call("GET", `${url}?${query()}`, undefined, viewer.request);
  assert.equal(response.status(), 200, await response.text());
  const data = await response.json();
  assert.equal(data.signals[0].samples.length, 4);
  assert.equal(data.signals[0].samples[1].value, null);
  assert.equal(data.signals[0].samples[1].raw, 999);
  assert.equal(data.signals[0].samples[2].sourceAt, null);
  assert.equal(data.signals[0].samples[0].receivedAt, at(10));
  assert.ok(data.events.some((event) => event.id === `alarm-${incident.id}` && event.at === at(-1)));
  assert.ok(data.events.some((event) => event.id === `classification-${reason.id}` && event.at === at(90)));
  assert.ok(data.events.some((event) => event.text === "Owned original operator observation"));
  assert.ok(!JSON.stringify(data).includes("CURRENT TEXT MUST NOT REWRITE HISTORY"));
  assert.ok(!JSON.stringify(data).includes("123456"));
  assert.deepEqual(data.events.map((event) => event.at), data.events.map((event) => event.at).toSorted());
  const textData = await (await call("GET", `${url}?${query({ keys: "ReplayText" })}`)).json();
  assert.equal(textData.signals[0].samples[0].raw.length, 512);
  assert.equal(textData.signals[0].samples[0].rawTruncated, true);
  for (const changes of [{ start: "2026-02-01T12:00:00" }, { end: at(-1) }, { end: "2026-02-04T12:00:00Z" }, { maxGapSeconds: "0" }, { maxGapSeconds: "3601" }]) assert.equal((await call("GET", `${url}?${query(changes)}`)).status(), 400, JSON.stringify(changes));
  const tooMany = query(); for (let i = 0; i < 8; i++) tooMany.append("keys", `Extra${i}`);
  assert.equal((await call("GET", `${url}?${tooMany}`)).status(), 400);
  assert.equal((await call("GET", `/api/v1/production/replay/2147483647?${query()}`)).status(), 404);
  const isolated = await (await call("GET", `/api/v1/production/replay/${other.id}?${query()}`)).json();
  assert.deepEqual(isolated.signals[0].samples.map((sample) => sample.value), [123456]);
  assert.ok(isolated.events.every((event) => !event.text.startsWith("Owned ")));

  await page.goto(`${frontend}/production`);
  await page.getByRole("tab", { name: "Incident replay", exact: true }).click();
  await page.getByLabel("Replay machine", { exact: true }).click();
  await page.getByRole("option", { name: machine.name, exact: true }).click();
  await page.getByLabel("Signal keys (comma separated, up to 8)").fill("ReplayCount");
  await page.getByLabel("Replay start (ISO with offset)").fill(at(0));
  await page.getByLabel("Replay end (ISO with offset)").fill(at(60));
  await page.getByLabel("Unknown after (seconds)").fill("5");
  await page.getByRole("button", { name: "Load replay", exact: true }).click();
  const observation = page.getByLabel("Replay observation ReplayCount");
  await expect(observation.getByRole("heading", { name: "10", exact: true })).toBeVisible();
  await page.getByLabel(`Review event ack-${incident.id}`).click();
  await expect(observation.getByRole("heading", { name: "Unknown", exact: true })).toBeVisible();
  await expect(observation).toContainText("Last raw value (not current): 999");
  const slider = page.getByRole("slider", { name: "Replay position" });
  await slider.focus(); for (let i = 0; i < 10; i++) await slider.press("ArrowRight");
  await expect(observation).toContainText("Observation gap");
  await expect(page.getByText("Owned original operator observation", { exact: true })).toBeVisible();
  await expect(page.getByText("Outside window context", { exact: true })).toHaveCount(2);
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export replay JSON", exact: true }).click();
  const exported = JSON.parse(await readFile(await (await download).path(), "utf8"));
  assert.deepEqual(exported.signals, data.signals);
  await page.getByRole("heading", { name: "Incident replay", exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: ".local/production-evidence/incident-replay.png", fullPage: true });
  await observation.scrollIntoViewIfNeeded();
  await page.screenshot({ path: ".local/production-evidence/incident-replay-events.png", fullPage: true });
  await page.getByRole("button", { name: "Play at 60×", exact: true }).click();
  await expect(page.getByLabel("Replay cursor")).toHaveText(at(60));
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: ".local/production-evidence/incident-replay-mobile.png", fullPage: true });
  await observation.scrollIntoViewIfNeeded();
  await page.screenshot({ path: ".local/production-evidence/incident-replay-mobile-observation.png", fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });

  await pool.query("INSERT INTO opcua_data(machine_id,node_key,timestamp,value,status_code) SELECT $1,'ReplayDense',$2::timestamptz+n*interval '1 millisecond',n,'Good' FROM generate_series(1,2001)n", [machine.id, at(0)]);
  await pool.query("INSERT INTO alert_history(machine_id,rule_name,message,created_at) SELECT $1,'Owned bounded alert','Owned limit fixture',$2::timestamptz+n*interval '1 millisecond' FROM generate_series(1,201)n", [machine.id, at(0)]);
  const bounded = await (await call("GET", `${url}?${query({ keys: "ReplayDense" })}`)).json();
  assert.equal(bounded.signals[0].samples.length, 2000);
  assert.equal(bounded.signals[0].truncated, true);
  assert.equal(bounded.truncated.alarms, true);
  await page.getByLabel("Signal keys (comma separated, up to 8)").fill("ReplayDense");
  await page.getByRole("button", { name: "Load replay", exact: true }).click();
  await expect(page.getByText(/Replay is truncated/)).toBeVisible();
  console.log("PASS: incident replay clocks, bad quality/gaps, immutable notes, retrospective classifications, machine isolation, viewer access, query bounds, playback, keyboard cursor and browser export");
}
