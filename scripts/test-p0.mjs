import assert from 'node:assert/strict';
import { mkdtemp, rm, mkdir, readFile, writeFile, copyFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve, dirname, basename } from 'node:path';
import { randomUUID } from 'node:crypto';
import pg from 'pg';
import dotenv from 'dotenv';
import { drizzle } from 'drizzle-orm/node-postgres';
import { migrate } from 'drizzle-orm/node-postgres/migrator';

dotenv.config({ path: 'server/.env', quiet: true });
assert.ok(['127.0.0.1', 'localhost'].includes(process.env.DB_HOST), 'P0 tests require the owned loopback database');
assert.equal(process.env.DB_PORT, '55432', 'P0 tests only use the isolated development database port');
const database = `pd_p0_${randomUUID().replaceAll('-', '')}`;
assert.match(database, /^pd_p0_[a-f0-9]{32}$/);
const directory = await mkdtemp(join(tmpdir(), 'dashboard-p0-'));
const admin = new pg.Client({ host: process.env.DB_HOST, port: 55432, user: process.env.DB_USER, password: process.env.DB_PASSWORD, database: 'postgres' });
let pool, manager, worker, created = false;
try {
  await admin.connect();
  await admin.query(`CREATE DATABASE "${database}"`);
  created = true;
  process.env.DB_NAME = database;
  process.env.DB_READ_REPLICA_URLS = '';
  process.env.DB_HEALTH_CHECK_INTERVAL = '0';
  process.env.OPCUA_SPOOL_PATH = join(directory, 'measurements.sqlite');
  process.env.LOG_LEVEL = 'error';
  pool = new pg.Pool({ host: process.env.DB_HOST, port: 55432, user: process.env.DB_USER, password: process.env.DB_PASSWORD, database });
  const previous = join(directory, 'previous-migrations');
  await mkdir(join(previous, 'meta'), { recursive: true });
  const journal = JSON.parse(await readFile('server/drizzle/meta/_journal.json', 'utf8'));
  journal.entries = journal.entries.filter(entry => entry.idx < 3);
  await writeFile(join(previous, 'meta/_journal.json'), JSON.stringify(journal));
  for (const entry of journal.entries) await copyFile(`server/drizzle/${entry.tag}.sql`, join(previous, `${entry.tag}.sql`));
  await migrate(drizzle(pool), { migrationsFolder: previous });
  await pool.query("INSERT INTO opcua_data(node_key,timestamp,value,raw_value,status_code) VALUES ('LegacyMigration',now(),7,'7','Good')");
  await migrate(drizzle(pool), { migrationsFolder: 'server/drizzle' });
  // Reapplying migrations must preserve both schema and existing data.
  await migrate(drizzle(pool), { migrationsFolder: 'server/drizzle' });
  const legacy = (await pool.query("SELECT value,raw_value,signal_metadata,received_at FROM opcua_data WHERE node_key='LegacyMigration'")).rows;
  assert.deepEqual(legacy, [{ value: 7, raw_value: 7, signal_metadata: null, received_at: null }]);
  ({ default: manager } = await import('../server/dist/src/database/dbConnection.js'));
  const { OpcuaQueueWorker } = await import('../server/dist/src/queue/opcuaQueueWorker.js');
  const { trendingDataService } = await import('../server/dist/src/services/trendingDataService.js');
  const { spcService } = await import('../server/dist/src/services/spcService.js');
  const { measurementIdentity } = await import('../server/dist/src/opc-ua/measurementIdentity.js');
  const machines = await pool.query("INSERT INTO machines(name,endpoint_url,ip,is_active) VALUES ('A','opc.tcp://owned-a:4841','localhost',false),('B','opc.tcp://owned-b:4841','localhost',false) RETURNING id");
  const [a, b] = machines.rows.map(row => row.id);
  const startDate = new Date('2026-01-01T00:00:00.000Z');
  const endDate = new Date('2026-01-01T00:00:05.000Z');
  await pool.query(`INSERT INTO opcua_data(node_key,timestamp,value,raw_value,status_code,machine_id)
    SELECT 'Dense', $1::timestamptz + g * interval '1 millisecond', CASE WHEN g=2500 THEN NULL ELSE g END,
      to_jsonb(g), CASE WHEN g=2500 THEN 'BadNoCommunication' ELSE 'Good' END, $2 FROM generate_series(0,5000) g`, [startDate, a]);
  await pool.query("INSERT INTO opcua_data(node_key,timestamp,value,status_code,machine_id) VALUES ('Dense',$1,999999,'Good',$2)", [startDate,b]);
  const result = await trendingDataService.queryTrendingData({ nodeKeys: ['Dense'], machineId: a, startDate, endDate });
  const series = result.series[0];
  assert.ok(series.data.length <= 2000);
  assert.equal(series.sampleCount, 5001);
  assert.equal(series.goodSampleCount, 5000);
  assert.equal(series.statistics.max, 5000);
  assert.equal(series.observedEnd, endDate.toISOString());
  assert.ok(new Date(series.data.at(-1).timestamp).getTime() >= endDate.getTime() - series.resolutionMs);
  assert.equal(series.data.reduce((sum, point) => sum + point.sampleCount, 0), 5001);
  assert.ok(series.data.some(point => point.statusCode === 'MixedOrBad' && point.value === null));
  assert.equal(series.legacySampleCount, 5001);
  await assert.rejects(trendingDataService.queryTrendingData({ nodeKeys: ['Dense'], startDate, endDate }), /one machine/);
  await assert.rejects(trendingDataService.queryTrendingData({ nodeKeys: ['Dense'], machineId: a, startDate: endDate, endDate: startDate }), /time window/);
  const long = await trendingDataService.queryTrendingData({ nodeKeys: ['Dense'], machineId: a, startDate, endDate: new Date(startDate.getTime()+86400000), downsampleBucketSeconds: 1 });
  assert.ok(long.series[0].data.length <= 2000);
  assert.ok(long.series[0].data.some(point => point.statusCode === 'Missing' && point.value === null));
  const signalMetadata = measurementIdentity('opc.tcp://owned-a:4841', a, 'Identity', { nodeId: 'ns=1;s=Identity', dataType: 'Double', label: 'Identity' }, ['core', 'urn:owned'], 'kW');
  worker = new OpcuaQueueWorker();
  worker.enqueue({ key: 'Identity', label: 'Identity', timestamp: startDate, receivedAt: endDate, value: 0, statusCode: 'Good', machineId: a, signalMetadata });
  await worker.stop();
  worker = new OpcuaQueueWorker();
  await worker.processBatch();
  const persisted = (await pool.query("SELECT * FROM opcua_data WHERE node_key='Identity'")).rows[0];
  assert.deepEqual(persisted.signal_metadata, signalMetadata);
  assert.equal(persisted.received_at.toISOString(), endDate.toISOString());
  const raw = (await trendingDataService.queryTrendingData({ nodeKeys: ['Identity'], machineId: a, startDate, endDate })).series[0];
  assert.equal(raw.data[0].value, 0);
  assert.equal(raw.data[0].receivedAt, endDate.toISOString());
  assert.equal(raw.legacySampleCount, 0);
  // Baselines must never include the second machine or legacy unknown quality.
  await pool.query("INSERT INTO opcua_data(node_key,timestamp,value,status_code,machine_id) VALUES ('Shared',now(),10,'Good',$1),('Shared',now(),20,'Good',$1),('Shared',now(),1000,'Good',$2),('Shared',now(),99999,NULL,$1)", [a,b]);
  const profile = (await pool.query("INSERT INTO spc_profiles(name,machine_id,node_key,method) VALUES ('A profile',$1,'Shared','zscore') RETURNING id", [a])).rows[0];
  const baseline = await spcService.computeBaseline(profile.id);
  assert.equal(baseline.mean, 15);
  const chart = await spcService.getChartData(profile.id, new Date(Date.now()-60000), new Date(Date.now()+60000));
  assert.equal(chart.dataPoints.length, 3);
  assert.ok(chart.dataPoints.every(point => point.value !== 1000));
  console.log('PASS: isolated fresh/repeated migrations, 5001-sample full-window trends, explicit bucket cap, same-key machine isolation, quality gaps, identity replay, legacy provenance and SPC baseline isolation');
} finally {
  await worker?.stop();
  await manager?.end();
  await pool?.end();
  if (created) await admin.query(`DROP DATABASE "${database}"`);
  await admin.end();
  assert.equal(dirname(resolve(directory)), resolve(tmpdir()));
  assert.ok(basename(directory).startsWith('dashboard-p0-'));
  await rm(directory, { recursive: true, force: true });
}
