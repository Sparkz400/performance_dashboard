import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { expect } from "@playwright/test";

export async function testUnattendedAlarms({ page, frontend, call, pool, machine, adminId, worker }) {
  await page.goto(`${frontend}/alerts/rules`);
  await page.getByRole("button", { name: /create rule/i }).click();
  await page.getByLabel(/^Name/).fill("Owned debounce");
  await page.getByLabel(/^Node Key/).fill("DebounceFixture");
  await page.getByLabel(/^Threshold/).fill("10");
  await page.getByLabel("Cooldown (seconds)").fill("0");
  await page.getByLabel("Trigger hold (seconds)").fill("2");
  await page.getByLabel("Recovery hold (seconds)").fill("2");
  await page.getByLabel("Recovery hysteresis (signal units)").fill("2");
  await page.getByLabel("Maximum sample gap (seconds)").fill("2");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.getByText("Owned debounce", { exact: true })).toBeVisible();
  const rule = (await pool.query("SELECT * FROM alert_rules WHERE name='Owned debounce'")).rows[0];
  assert.equal(rule.debounce_seconds, 2);
  assert.equal(rule.clear_debounce_seconds, 2);
  assert.equal(rule.hysteresis, 2);
  assert.equal((await call("PUT", `/api/v1/alerts/rules/${rule.id}`, { condition: "eq" })).status(), 400);
  const { AlarmEvaluator } = await import("../server/dist/src/services/alarmService.js");
  let evaluator = new AlarmEvaluator();
  const beginning = Date.now();
  const point = (seconds, value, statusCode = "Good") => ({ id: randomUUID(), data: { machineId: machine.id, key: "DebounceFixture", label: "Owned debounce fixture", timestamp: new Date(beginning + seconds * 1000), receivedAt: new Date(beginning + seconds * 1000), sourceTimestamp: new Date(beginning + seconds * 1000), value, statusCode } });
  const incidents = async () => (await pool.query("SELECT * FROM alert_history WHERE rule_id=$1 ORDER BY id", [rule.id])).rows;
  await evaluator.evaluate(point(0, 12));
  await evaluator.evaluate(point(1, 8));
  assert.equal((await incidents()).length, 0, "Short spike must not create an incident");
  await evaluator.evaluate(point(2, 12));
  evaluator = new AlarmEvaluator();
  await evaluator.evaluate(point(3, 12));
  const trigger = point(4, 12);
  await evaluator.evaluate(trigger); await evaluator.evaluate(trigger);
  assert.equal((await incidents()).length, 1);
  const incident = (await incidents())[0];
  await evaluator.acknowledge(incident.id, adminId);
  await evaluator.evaluate(point(5, 9));
  assert.equal((await incidents())[0].resolved_at, null, "Hysteresis retains the acknowledged incident");
  await evaluator.evaluate(point(6, 7));
  await evaluator.evaluate(point(7, 7, "Uncertain"));
  assert.equal((await incidents())[0].metadata.conditionState, "unknown");
  await evaluator.evaluate(point(8, 7));
  await evaluator.evaluate(point(9, 7));
  assert.equal((await incidents())[0].resolved_at, null);
  await evaluator.evaluate(point(10, 7));
  assert.ok((await incidents())[0].resolved_at);
  assert.equal((await incidents())[0].acknowledged_by, adminId);

  const { healthIncidentService } = await import("../server/dist/src/services/healthIncidentService.js");
  const profile = (await pool.query("SELECT profile FROM machine_profiles WHERE machine_id=$1 ORDER BY id DESC LIMIT 1", [machine.id])).rows[0].profile;
  const signal = profile.signals.state;
  const insertState = async (stale, statusCode = 'Good') => {
    const at = new Date();
    await pool.query("INSERT INTO opcua_data(machine_id,node_key,timestamp,source_timestamp,received_at,value,status_code,signal_metadata) VALUES ($1,$2,$3,$4,$3,$5,$7,$6)", [machine.id, signal.nodeKey, at, stale ? new Date(at.getTime() - 300000) : at, profile.states.running[0] / signal.scale, { namespaceUri: signal.namespaceUri, identifier: signal.identifier }, statusCode]);
  };
  await insertState(true);
  await healthIncidentService.check();
  const healthRows = async (key) => (await pool.query("SELECT * FROM alert_history WHERE metadata->>'healthKey'=$1 ORDER BY id", [key])).rows;
  let rows = await healthRows(`machine-${machine.id}`);
  assert.equal(rows.length, 1);
  assert.equal(rows[0].resolved_at, null);
  await insertState(false); await healthIncidentService.check();
  rows = await healthRows(`machine-${machine.id}`);
  assert.ok(rows[0].resolved_at, "Fresh observed data must clear the stale-data incident");
  await pool.query("UPDATE machines SET status='disconnected' WHERE id=$1", [machine.id]);
  await healthIncidentService.check();
  assert.match((await healthRows(`machine-${machine.id}`)).at(-1).message, /disconnected/);
  await pool.query("UPDATE machines SET status='connected' WHERE id=$1", [machine.id]);
  await insertState(false, 'Uncertain'); await healthIncidentService.check();
  assert.match((await healthRows(`machine-${machine.id}`)).at(-1).message, /bad-quality/);
  assert.equal((await healthRows(`machine-${machine.id}`)).at(-1).resolved_at, null);
  await insertState(false); await healthIncidentService.check();
  assert.ok((await healthRows(`machine-${machine.id}`)).at(-1).resolved_at);
  const originalHealth = worker.getHealth;
  const healthy = originalHealth.call(worker);
  try {
    worker.getHealth = () => ({ ...healthy, storageFailure: { at: new Date().toISOString(), message: "Owned injected storage failure" }, pendingMeasurements: 2, oldestReceivedAgeSeconds: 120 });
    await healthIncidentService.check(); await healthIncidentService.check();
    assert.equal((await healthRows("collector-storage")).length, 1);
    assert.equal((await healthRows("collector-backlog")).length, 1);
    worker.getHealth = () => ({ ...healthy, storageFailure: null, pendingMeasurements: 0, oldestReceivedAgeSeconds: null, unknownReceiveTimes: 0 });
    await healthIncidentService.check();
    assert.ok((await healthRows("collector-storage"))[0].resolved_at);
    assert.ok((await healthRows("collector-backlog"))[0].resolved_at);
    // H09: a young backlog near the capacity stop still alerts while samples are accepted.
    worker.getHealth = () => ({ ...healthy, storageFailure: null, pendingMeasurements: 800, capacityMeasurements: 1000, oldestReceivedAgeSeconds: 1, unknownReceiveTimes: 0 });
    await healthIncidentService.check();
    const nearCapacity = (await healthRows("collector-backlog")).at(-1);
    assert.equal(nearCapacity.resolved_at, null);
    assert.match(nearCapacity.message, /800 of 1000/);
  } finally { worker.getHealth = originalHealth; await healthIncidentService.stop(); }
  console.log("PASS: browser alarm holds/hysteresis, durable pending state, bad-quality recovery reset, machine freshness and collector incidents");
}
